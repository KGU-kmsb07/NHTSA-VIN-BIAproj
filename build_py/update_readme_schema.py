def make_table(rows):
    header = "| 필드 번호 | 원본 필드명 | 처리 구분 | 최종 반영 변수명 | 채택 사유 또는 제외 사유 (Rationale) |\n|:---:|---|:---:|:---:|---|\n"
    lines = []
    for r in rows:
        lines.append(f"| {r[0]} | {r[1]} | {r[2]} | {r[3]} | {r[4]} |")
    return header + "\n".join(lines) + "\n"

